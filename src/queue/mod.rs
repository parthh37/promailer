#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
#[serde(tag = "type", rename_all = "lowercase")]
pub enum Source {
    Smtp {
        ip: IpAddr,
        user: Option<String>,
    },
    Pickup {
        file: String,
    },
    Api {
        key: String,
    },
    /// Delivery status notification generated by this server.
    Ndr {
        original: String,
    },
}

#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "lowercase")]
pub enum RcptStatus {
    Pending,
    Delivered,
    Failed,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RecipientState {
    pub address: String,
    pub status: RcptStatus,
    #[serde(default)]
    pub attempts: u32,
    #[serde(default)]
    pub last_response: Option<String>,
    #[serde(default)]
    pub remote_host: Option<String>,
    #[serde(default)]
    pub updated: Option<DateTime<Utc>>,
}

impl RecipientState {
    pub fn domain(&self) -> String {
        message::domain_of(&self.address)
    }
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct QueueEntry {
    pub id: String,
    pub created: DateTime<Utc>,
    /// Envelope sender; empty for the null reverse-path (bounces).
    pub sender: String,
    pub recipients: Vec<RecipientState>,
    pub source: Source,
    pub size: u64,
    #[serde(default)]
    pub pool: Option<String>,
    #[serde(default)]
    pub dkim: Vec<String>,
    #[serde(default)]
    pub attempts: u32,
    pub next_attempt: DateTime<Utc>,
    #[serde(default)]
    pub last_attempt: Option<DateTime<Utc>>,
    #[serde(default)]
    pub delay_notified: bool,
    /// Decoded Subject header, for display and search.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub subject: Option<String>,
}

impl QueueEntry {
    pub fn is_ndr(&self) -> bool {
        matches!(self.source, Source::Ndr { .. })
    }
    pub fn pending(&self) -> impl Iterator<Item = &RecipientState> {
        self.recipients.iter().filter(|r| r.status == RcptStatus::Pending)
    }

    /// Start a lifecycle event for this message.
    pub fn event(&self, kind: EventKind) -> Event {
        let mut ev = Event::new(&self.id, kind, &self.sender);
        ev.subject = self.subject.clone();
        ev
    }

    /// Case-insensitive search over ID, sender, recipients and subject. `needle` must be lowercase.
    pub fn matches(&self, needle: &str) -> bool {
        let hit = |s: &str| s.to_lowercase().contains(needle);
        hit(&self.id)
            || hit(&self.sender)
            || self.subject.as_deref().is_some_and(hit)
            || self.recipients.iter().any(|r| hit(&r.address) || r.last_response.as_deref().is_some_and(hit))
    }
}

/// A message about to be queued.
pub struct NewMessage {
    pub sender: String,
    pub recipients: Vec<String>,
    pub data: Vec<u8>,
    pub source: Source,
    pub pool: Option<String>,
}

// ---------------------------------------------------------------------------
// In-memory scheduler
// ---------------------------------------------------------------------------

#[derive(Default)]
struct Sched {
    /// Every queued message and the time (ms since epoch) it's due.
    entries: HashMap<Ulid, i64>,
    /// Messages waiting for their due time (not currently being delivered).
    waiting: BTreeSet<(i64, Ulid)>,
    in_flight: HashSet<Ulid>,
}

pub struct Queue {
    pub store: Store,
    sched: Mutex<Sched>,
    notify: Notify,
    pub(crate) routes: delivery::Routes,
}

#[derive(Debug, PartialEq, Eq)]
pub enum QueueOpError {
    NotFound,
    InFlight,
}

impl Queue {
    pub fn open(store: Store) -> Result<Arc<Self>> {
        let q = Arc::new(Self {
            store,
            sched: Mutex::new(Sched::default()),
            notify: Notify::new(),
            routes: delivery::Routes::default(),
        });
        let recovered = q.store.recover()?;
        let n = recovered.len();
        {
            let mut s = q.sched.lock();
            for e in recovered {
                if let Ok(id) = Ulid::from_string(&e.id) {
                    let t = e.next_attempt.timestamp_millis();
                    s.entries.insert(id, t);
                    s.waiting.insert((t, id));
                }
            }
        }
        if n > 0 {
            info!(count = n, "recovered queued messages from disk");
        }
        Ok(q)
    }

    pub fn len(&self) -> usize {
        self.sched.lock().entries.len()
    }

    pub fn in_flight(&self) -> usize {
        self.sched.lock().in_flight.len()
    }

    fn schedule(&self, id: Ulid, at: DateTime<Utc>) {
        let t = at.timestamp_millis();
        let mut s = self.sched.lock();
        s.in_flight.remove(&id);
        if let Some(old) = s.entries.insert(id, t) {
            s.waiting.remove(&(old, id));
        }
        s.waiting.insert((t, id));
        drop(s);
        self.notify.notify_one();
    }

    fn finish(&self, id: Ulid) {
        let mut s = self.sched.lock();
        s.in_flight.remove(&id);
        if let Some(t) = s.entries.remove(&id) {
            s.waiting.remove(&(t, id));
        }
    }

    /// Pop up to `max` due messages and mark them in flight.
    fn take_due(&self, max: usize) -> Vec<Ulid> {
        let now = Utc::now().timestamp_millis();
        let mut s = self.sched.lock();
        let mut out = Vec::new();
        while out.len() < max {
            let Some(&(t, id)) = s.waiting.first() else { break };
            if t > now {
                break;
            }
            s.waiting.pop_first();
            s.in_flight.insert(id);
            out.push(id);
        }
        out
    }

    fn next_due_in(&self) -> Option<Duration> {
        let s = self.sched.lock();
        let (t, _) = s.waiting.first()?;
        let now = Utc::now().timestamp_millis();
        Some(Duration::from_millis((*t - now).max(0) as u64))
    }

    /// API/CLI: deliver now.
    pub fn retry_now(&self, id: &str) -> Result<(), QueueOpError> {
        let id = Ulid::from_string(id).map_err(|_| QueueOpError::NotFound)?;
        {
            let s = self.sched.lock();
            if !s.entries.contains_key(&id) {
                return Err(QueueOpError::NotFound);
            }
            if s.in_flight.contains(&id) {
                return Err(QueueOpError::InFlight);
            }
        }
        self.schedule(id, Utc::now());
        Ok(())
    }

    pub fn retry_all(&self) -> usize {
        let ids: Vec<Ulid> = {
            let s = self.sched.lock();
            s.waiting.iter().map(|(_, id)| *id).collect()
        };
        let now = Utc::now();
        for id in &ids {
            self.schedule(*id, now);
        }
        ids.len()
    }

    /// API/CLI: remove a message from the queue without sending an NDR.
    pub fn delete(&self, id: &str) -> Result<(), QueueOpError> {
        let uid = Ulid::from_string(id).map_err(|_| QueueOpError::NotFound)?;
        {
            let mut s = self.sched.lock();
            if s.in_flight.contains(&uid) {
                return Err(QueueOpError::InFlight);
            }
            let Some(t) = s.entries.remove(&uid) else { return Err(QueueOpError::NotFound) };
            s.waiting.remove(&(t, uid));
        }
        if let Err(e) = self.store.delete(id) {
            error!(%id, error = %e, "failed to delete queue files");
        }
        info!(target: DELIVERY_TARGET, "{id} deleted by administrator");
        Ok(())
    }
}

// ---------------------------------------------------------------------------
// Enqueue (shared by SMTP, Pickup, API and NDR generation)
// ---------------------------------------------------------------------------

pub async fn enqueue(app: &Arc<App>, msg: NewMessage) -> Result<String> {
    if msg.recipients.is_empty() {
        bail!("message has no recipients");
    }
    let cfg = app.cfg();
    let hostname = cfg.server.hostname.clone();
    let from_fallback = match msg.source {
        Source::Smtp { .. } => None,
        _ => Some(msg.sender.clone()),
    };
    let dkim = app.dkim.load_full();

    // CRLF normalisation, header completion and DKIM signing are CPU work on
    // potentially large buffers: keep them off the async executor threads.
    let (data, signed_by, subject) = tokio::task::spawn_blocking(move || {
        let data = message::normalize_crlf(msg.data);
        let data = message::complete_headers(data, &hostname, from_fallback.as_deref());
        let subject = message::subject(&data);
        let (data, signed_by) = dkim.sign(data);
        (data, signed_by, subject)
    })
    .await
    .context("message preparation task failed")?;

    let now = Utc::now();
    let id = Ulid::new();
    let mut seen = HashSet::new();
    let recipients: Vec<RecipientState> = msg
        .recipients
        .into_iter()
        .filter(|r| seen.insert(r.to_lowercase()))
        .map(|address| RecipientState {
            address,
            status: RcptStatus::Pending,
            attempts: 0,
            last_response: None,
            remote_host: None,
            updated: None,
        })
        .collect();
    let entry = QueueEntry {
        id: id.to_string(),
        created: now,
        sender: msg.sender,
        recipients,
        source: msg.source,
        size: data.len() as u64,
        pool: msg.pool,
        dkim: signed_by,
        attempts: 0,
        next_attempt: now,
        last_attempt: None,
        delay_notified: false,
        subject,
    };

    let q = app.queue.clone();
    let e2 = entry.clone();
    tokio::task::spawn_blocking(move || q.store.create(&e2, &data)).await.context("queue write task failed")??;

    info!(
        target: DELIVERY_TARGET,
        "{} queued from=<{}> rcpts={} size={} source={} dkim={}",
        entry.id,
        entry.sender,
        entry.recipients.len(),
        entry.size,
        source_label(&entry.source),
        if entry.dkim.is_empty() { "none".to_string() } else { entry.dkim.join(",") }
    );
    let mut ev = entry.event(EventKind::Queued);
    ev.to = Some(entry.recipients.iter().map(|r| r.address.as_str()).collect::<Vec<_>>().join(", "));
    ev.detail = Some(format!("size={} source={}", entry.size, source_label(&entry.source)));
    app.events.record(ev);
    app.queue.schedule(id, now);
    Ok(entry.id)
}

fn source_label(s: &Source) -> String {
    match s {
        Source::Smtp { ip, user: Some(u) } => format!("smtp:{ip}:{u}"),
        Source::Smtp { ip, user: None } => format!("smtp:{ip}"),
        Source::Pickup { file } => format!("pickup:{file}"),
        Source::Api { key } => format!("api:{key}"),
        Source::Ndr { original } => format!("ndr:{original}"),
    }
}

// ---------------------------------------------------------------------------
// Scheduler loop
// ---------------------------------------------------------------------------

pub async fn run(app: Arc<App>) {
    let max = app.cfg().delivery.max_concurrent_messages;
    let permits = Arc::new(Semaphore::new(max));
    let mut shutdown = app.shutdown_rx();
    info!(max_concurrent_messages = max, "delivery scheduler started");

    loop {
        if app.is_shutting_down() {
            break;
        }
        let available = permits.available_permits();
        let due = if available > 0 { app.queue.take_due(available) } else { Vec::new() };
        let got_work = !due.is_empty();
        for id in due {
            let Ok(permit) = permits.clone().try_acquire_owned() else {
                // Should not happen (we only took `available`), but never lose a message.
                app.queue.schedule(id, Utc::now());
                continue;
            };
            let app = app.clone();
            tokio::spawn(async move {
                process_guarded(app, id, permit).await;
            });
        }
        if got_work {
            tokio::task::yield_now().await;
            continue;
        }
        let scan = app.cfg().delivery.queue_scan_interval;
        let wait = app.queue.next_due_in().map(|d| d.min(scan)).unwrap_or(scan);
        tokio::select! {
            _ = tokio::time::sleep(wait) => {}
            _ = app.queue.notify.notified() => {}
            _ = shutdown.changed() => break,
        }
    }

    // Graceful drain: wait for in-flight deliveries up to the grace period.
    let grace = app.cfg().server.shutdown_grace;
    let all = max as u32;
    let drained = tokio::time::timeout(grace, permits.clone().acquire_many_owned(all)).await;
    match drained {
        Ok(_) => info!("delivery scheduler stopped cleanly"),
        Err(_) => warn!(
            in_flight = app.queue.in_flight(),
            "shutdown grace period elapsed with deliveries in flight; they will be retried on next start"
        ),
    }
}

/// Runs `process` in its own task so a panic is contained and the message is
/// rescheduled rather than silently stuck "in flight" forever.
async fn process_guarded(app: Arc<App>, id: Ulid, permit: OwnedSemaphorePermit) {
    let app2 = app.clone();
    let res = tokio::spawn(async move { process(app2, id).await }).await;
    match res {
        Ok(Ok(())) => {}
        Ok(Err(e)) => {
            error!(id = %id, error = format!("{e:#}"), "delivery processing error; will retry");
            app.queue.schedule(id, Utc::now() + chrono::Duration::minutes(5));
        }
        Err(join_err) => {
            error!(id = %id, error = %join_err, "delivery task panicked; will retry");
            app.queue.schedule(id, Utc::now() + chrono::Duration::minutes(5));
        }
    }
    drop(permit);
}

async fn process(app: Arc<App>, id: Ulid) -> Result<()> {
    let cfg = app.cfg();
    let sid = id.to_string();
    let q = app.queue.clone();
    let sid2 = sid.clone();
    let loaded = tokio::task::spawn_blocking(move || -> Result<(QueueEntry, Vec<u8>)> {
        Ok((q.store.load_meta(&sid2)?, q.store.load_data(&sid2)?))
    })
    .await?;
    let (mut entry, data) = match loaded {
        Ok(v) => v,
        Err(e) => {
            error!(id = %sid, error = format!("{e:#}"), "queue entry unreadable; dropping from schedule");
            app.queue.finish(id);
            return Ok(());
        }
    };
    let data = Arc::new(data);
    let now = Utc::now();
    let expired = now.signed_duration_since(entry.created).to_std().unwrap_or_default() >= cfg.delivery.expire_after;

    if expired {
        let hours = cfg.delivery.expire_after.as_secs() / 3600;
        for r in entry.recipients.iter_mut().filter(|r| r.status == RcptStatus::Pending) {
            let last = r.last_response.clone().unwrap_or_else(|| "no response".into());
            r.status = RcptStatus::Failed;
            r.last_response = Some(format!("Message expired after {hours} hours in queue. Last error: {last}"));
            r.updated = Some(now);
            Stats::inc(&app.stats.recipients_bounced);
            info!(target: DELIVERY_TARGET, "{} to=<{}> status=expired detail=\"{}\"", entry.id, r.address, r.last_response.as_deref().unwrap_or(""));
            let mut ev = Event::new(&entry.id, EventKind::Expired, &entry.sender);
            ev.subject = entry.subject.clone();
            ev.to = Some(r.address.clone());
            ev.attempt = Some(r.attempts);
            ev.detail = r.last_response.clone();
            app.events.record(ev);
        }
    } else {
        attempt_delivery(&app, &mut entry, data.clone()).await;
    }

    entry.attempts += 1;
    entry.last_attempt = Some(now);

    if entry.pending().next().is_none() {
        finalize(&app, &entry, &data).await;
        let q = app.queue.clone();
        let sid2 = sid.clone();
        tokio::task::spawn_blocking(move || q.store.delete(&sid2)).await??;
        app.queue.finish(id);
        return Ok(());
    }

    // Delay notification (once).
    let delay = cfg.delivery.delay_notification_after;
    if !delay.is_zero()
        && !entry.delay_notified
        && !entry.sender.is_empty()
        && !entry.is_ndr()
        && cfg.delivery.send_ndr
        && now.signed_duration_since(entry.created).to_std().unwrap_or_default() >= delay
    {
        if let Err(e) = dsn::send_delay(&app, &entry, &data).await {
            warn!(id = %sid, error = %e, "failed to generate delay notification");
        }
        entry.delay_notified = true;
    }

    let intervals = &cfg.delivery.retry_intervals;
    let idx = (entry.attempts as usize).saturating_sub(1).min(intervals.len() - 1);
    let mut next = now + chrono::Duration::from_std(intervals[idx]).unwrap_or(chrono::Duration::minutes(15));
    // Make sure the last attempt happens at expiry time rather than after it.
    let expiry =
        entry.created + chrono::Duration::from_std(cfg.delivery.expire_after).unwrap_or(chrono::Duration::days(2));
    if next > expiry {
        next = expiry.max(now + chrono::Duration::seconds(30));
    }
    entry.next_attempt = next;
    let q = app.queue.clone();
    let e2 = entry.clone();
    tokio::task::spawn_blocking(move || q.store.update(&e2)).await??;
    app.queue.schedule(id, next);
    Ok(())
}

async fn attempt_delivery(app: &Arc<App>, entry: &mut QueueEntry, data: Arc<Vec<u8>>) {
    let cfg = app.cfg();
    // Group pending recipients by destination domain.
    let mut groups: HashMap<String, Vec<String>> = HashMap::new();
    for r in entry.pending() {
        groups.entry(r.domain()).or_default().push(r.address.clone());
    }

    let mut outcomes: Vec<(String, delivery::Outcome)> = Vec::new();

    // Local domains: IIS-style Drop directory.
    let local: Vec<String> = groups.keys().filter(|d| cfg.is_local_domain(d)).cloned().collect();
    for d in local {
        let rcpts = groups.remove(&d).unwrap_or_default();
        let q = app.queue.clone();
        let (id, sender, data2, r2) = (entry.id.clone(), entry.sender.clone(), data.clone(), rcpts.clone());
        let res = tokio::task::spawn_blocking(move || q.store.write_drop(&id, &sender, &r2, &data2)).await;
        let outcome = match res {
            Ok(Ok(())) => {
                delivery::Outcome::Delivered { host: "drop".into(), response: "250 written to Drop directory".into() }
            }
            Ok(Err(e)) => {
                delivery::Outcome::Transient { host: None, response: format!("drop directory write failed: {e:#}") }
            }
            Err(e) => delivery::Outcome::Transient { host: None, response: format!("drop task failed: {e}") },
        };
        outcomes.extend(rcpts.into_iter().map(|r| (r, outcome.clone())));
    }

    // Remote domains in parallel; connection limits are enforced inside.
    let futs = groups.into_iter().map(|(domain, rcpts)| {
        let app = app.clone();
        let data = data.clone();
        let sender = entry.sender.clone();
        let pool = entry.pool.clone();
        let id = entry.id.clone();
        async move { delivery::deliver_domain(&app, &id, &sender, &domain, &rcpts, &data, pool.as_deref()).await }
    });
    for res in futures::future::join_all(futs).await {
        outcomes.extend(res);
    }

    let now = Utc::now();
    for (addr, outcome) in outcomes {
        let Some(r) = entry.recipients.iter_mut().find(|r| r.address == addr && r.status == RcptStatus::Pending) else {
            continue;
        };
        r.attempts += 1;
        r.updated = Some(now);
        let (status, label, kind) = match &outcome {
            delivery::Outcome::Delivered { .. } => (RcptStatus::Delivered, "sent", EventKind::Sent),
            delivery::Outcome::Permanent { .. } => (RcptStatus::Failed, "bounced", EventKind::Bounced),
            delivery::Outcome::Transient { .. } => (RcptStatus::Pending, "deferred", EventKind::Deferred),
        };
        let (host, response) = outcome.parts();
        r.status = status;
        r.remote_host = host.clone().or(r.remote_host.take());
        r.last_response = Some(response.clone());
        match status {
            RcptStatus::Delivered => Stats::inc(&app.stats.recipients_delivered),
            RcptStatus::Failed => Stats::inc(&app.stats.recipients_bounced),
            RcptStatus::Pending => Stats::inc(&app.stats.recipients_deferred),
        }
        info!(
            target: DELIVERY_TARGET,
            "{} from=<{}> to=<{}> status={} attempt={} relay={} delay={}s response=\"{}\"",
            entry.id,
            entry.sender,
            r.address,
            label,
            r.attempts,
            host.as_deref().unwrap_or("-"),
            now.signed_duration_since(entry.created).num_seconds(),
            response.replace('"', "'")
        );
        let mut ev = Event::new(&entry.id, kind, &entry.sender);
        ev.subject = entry.subject.clone();
        ev.to = Some(r.address.clone());
        ev.relay = host;
        ev.attempt = Some(r.attempts);
        ev.detail = Some(response);
        app.events.record(ev);
    }
}

/// All recipients are final: generate NDRs or move undeliverable bounces to badmail.
async fn finalize(app: &Arc<App>, entry: &QueueEntry, data: &[u8]) {
    let failed: Vec<&RecipientState> = entry.recipients.iter().filter(|r| r.status == RcptStatus::Failed).collect();
    if failed.is_empty() {
        return;
    }
    let cfg = app.cfg();
    if entry.sender.is_empty() || entry.is_ndr() {
        // Never bounce a bounce (RFC 5321 §6.1): park it in badmail.
        let reason = failed
            .iter()
            .map(|r| format!("{}: {}", r.address, r.last_response.as_deref().unwrap_or("")))
            .collect::<Vec<_>>()
            .join("\r\n");
        let q = app.queue.clone();
        let (id, d) = (entry.id.clone(), data.to_vec());
        let reason = format!("Undeliverable message with null sender.\r\n{reason}\r\n");
        let _ = tokio::task::spawn_blocking(move || q.store.write_badmail(&id, &d, &reason)).await;
        Stats::inc(&app.stats.badmail);
        warn!(id = %entry.id, "undeliverable bounce moved to badmail");
        return;
    }
    if cfg.delivery.send_ndr {
        match dsn::send_failure(app, entry, data).await {
            Ok(ndr_id) => {
                Stats::inc(&app.stats.ndr_generated);
                info!(target: DELIVERY_TARGET, "{} ndr generated id={} to=<{}>", entry.id, ndr_id, entry.sender);
                let mut ev = entry.event(EventKind::Ndr);
                ev.to = Some(entry.sender.clone());
                ev.detail = Some(format!("non-delivery report queued as {ndr_id}"));
                app.events.record(ev);
            }
            Err(e) => {
                error!(id = %entry.id, error = %e, "failed to generate NDR; moving to badmail");
                let q = app.queue.clone();
                let (id, d) = (entry.id.clone(), data.to_vec());
                let _ =
                    tokio::task::spawn_blocking(move || q.store.write_badmail(&id, &d, "NDR generation failed")).await;
            }
        }
    }
}
